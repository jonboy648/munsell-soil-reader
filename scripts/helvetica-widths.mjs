// Writes src/delineation/helveticaWidths.ts: the width of every character the PDF's Helvetica can
// print (WinAnsi), in thousandths of the text size, as pdf-lib measures it. The form engine
// measures text from this table, so it needs no PDF library to know what fits in a column.
//
//   node scripts/helvetica-widths.mjs
import { writeFile } from "node:fs/promises"
import { PDFDocument, StandardFonts } from "pdf-lib"

const doc = await PDFDocument.create()
const font = await doc.embedFont(StandardFonts.Helvetica)

// Every character a WinAnsi font can have: Latin-1, and the extras Windows put in 0x80-0x9F.
const candidates = [
  ...Array.from({ length: 0x7e - 0x20 + 1 }, (_, i) => 0x20 + i),
  ...Array.from({ length: 0xff - 0xa0 + 1 }, (_, i) => 0xa0 + i),
  ...[0x20ac, 0x201a, 0x0192, 0x201e, 0x2026, 0x2020, 0x2021, 0x02c6, 0x2030, 0x0160, 0x2039, 0x0152, 0x017d],
  ...[0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2013, 0x2014, 0x02dc, 0x2122, 0x0161, 0x203a, 0x0153, 0x017e, 0x0178],
]

const widths = {}
for (const code of candidates) {
  const ch = String.fromCodePoint(code)
  try {
    font.encodeText(ch)
  } catch {
    continue // not in WinAnsi
  }
  widths[ch] = Math.round(font.widthOfTextAtSize(ch, 1000))
}

const lines = Object.entries(widths).map(([ch, w]) => `  ${JSON.stringify(ch)}: ${w},`)
await writeFile(
  new URL("../src/delineation/helveticaWidths.ts", import.meta.url),
  `// Generated by scripts/helvetica-widths.mjs. Do not edit.\n` +
    `// Each character Helvetica can print in a PDF (WinAnsi), and its width in thousandths of the text size.\n` +
    `export const HELVETICA_WIDTHS: Readonly<Record<string, number>> = {\n${lines.join("\n")}\n}\n`,
)
console.log(`${Object.keys(widths).length} characters`)
